// Builds the Commands / Variables / uo.dll sidebar groups from the pages' own frontmatter.
//
// Starlight can only autogenerate a sidebar from folders, and folders would put the category in
// the URL (/commands/client/finditem/), which would break links whenever an entry is
// re-categorised. So pages live flat (/commands/finditem/) and this reads `title`, `category`
// and `sidebar.order` from each file at config time instead.

import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { COMMAND_CATEGORIES, VARIABLE_CATEGORIES, DLL_CATEGORIES } from './reference.mjs';

const DOCS = fileURLToPath(new URL('./content/docs/', import.meta.url));

function walk(dir) {
	let files = [];
	for (const name of readdirSync(dir)) {
		const full = join(dir, name);
		if (statSync(full).isDirectory()) files = files.concat(walk(full));
		else if (/\.mdx?$/.test(name)) files.push(full);
	}
	return files;
}

// Only the handful of flat top-level keys the sidebar needs; the real validation is the
// content collection schema.
function frontmatter(file) {
	const m = readFileSync(file, 'utf8').match(/^---\r?\n([\s\S]*?)\r?\n---/);
	const data = {};
	if (!m) return data;
	let inSidebar = false;
	for (const line of m[1].split(/\r?\n/)) {
		const kv = line.match(/^(\s*)([A-Za-z]+):\s*(.*?)\s*$/);
		if (!kv) continue;
		const [, indent, key, raw] = kv;
		const value = raw.replace(/^(['"])(.*)\1$/, '$2');
		if (!indent) {
			inSidebar = key === 'sidebar';
			data[key] = value;
		} else if (inSidebar && key === 'order') data.order = Number(value);
		else if (inSidebar && key === 'label') data.sidebarLabel = value;
	}
	return data;
}

function slugOf(file) {
	return relative(DOCS, file)
		.split(sep)
		.join('/')
		.replace(/\.mdx?$/, '')
		.replace(/\/index$/, '')
		.toLowerCase();
}

function groupFor(section, categories, overview) {
	const dir = join(DOCS, section);
	if (!existsSync(dir)) return null;
	const entries = walk(dir)
		.map((file) => ({ file, slug: slugOf(file), ...frontmatter(file) }))
		.filter((e) => e.kind);
	const items = [{ label: overview, slug: section }];
	for (const [key, label] of categories) {
		const inCat = entries
			.filter((e) => e.category === key)
			.sort((a, b) => (a.order ?? 0) - (b.order ?? 0) || a.title.localeCompare(b.title));
		if (!inCat.length) continue;
		items.push({
			label,
			collapsed: true,
			items: inCat.map((e) => ({ label: e.sidebarLabel || e.title, slug: e.slug })),
		});
	}
	return items;
}

// A section whose folder does not exist yet is left out, so later sections only need their folder.
export function referenceSidebar() {
	return [
		{ label: 'Commands', items: groupFor('commands', COMMAND_CATEGORIES, 'All commands (A–Z)') },
		{ label: 'Variables', items: groupFor('variables', VARIABLE_CATEGORIES, 'All variables (A–Z)') },
		{ label: 'uo.dll API', collapsed: true, items: groupFor('dll', DLL_CATEGORIES, 'Overview') },
	].filter((group) => group.items);
}

// Plain autogenerated group for a prose folder (guide/, language/, ...), if it exists.
export function folderGroup(label, directory, collapsed = false) {
	return existsSync(join(DOCS, directory)) ? [{ label, collapsed, items: [{ autogenerate: { directory } }] }] : [];
}
